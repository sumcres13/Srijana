document.querySelectorAll('[data-access-gallery]').forEach((gallery) => {
  const photos = [...gallery.querySelectorAll('.access-gallery-images img')];
  const thumbnails = [...gallery.querySelectorAll('[data-gallery-select]')];
  const count = gallery.querySelector('.access-gallery-count');
  const arrows = [...gallery.querySelectorAll('[data-gallery-step]')];
  const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
  let current = 0;
  let timer;

  function restartAutoplay() {
    clearInterval(timer);
    if (reducedMotion.matches) return;
    timer = setInterval(() => {
      if (document.hidden || gallery.matches(':hover') || gallery.contains(document.activeElement)) return;
      showPhoto(current + 1);
    }, 3000);
  }

  function selectPhoto(index) {
    showPhoto(index);
    restartAutoplay();
  }

  function showPhoto(index) {
    current = (index + photos.length) % photos.length;
    photos.forEach((photo, position) => {
      const active = position === current;
      photo.classList.toggle('is-active', active);
      photo.setAttribute('aria-hidden', String(!active));
    });
    thumbnails.forEach((thumbnail, position) => {
      thumbnail.setAttribute('aria-current', String(position === current));
    });
    count.textContent = `${String(current + 1).padStart(2, '0')} / ${String(photos.length).padStart(2, '0')}`;
  }

  thumbnails.forEach((thumbnail) => {
    thumbnail.addEventListener('click', () => selectPhoto(Number(thumbnail.dataset.gallerySelect)));
  });
  arrows.forEach((arrow) => {
    arrow.hidden = false;
    arrow.addEventListener('click', () => selectPhoto(current + Number(arrow.dataset.galleryStep)));
  });
  gallery.addEventListener('keydown', (event) => {
    if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
    event.preventDefault();
    selectPhoto(current + (event.key === 'ArrowRight' ? 1 : -1));
  });
  showPhoto(current);
  photos.forEach((photo) => {
    photo.loading = 'eager';
    photo.hidden = false;
  });
  reducedMotion.addEventListener('change', restartAutoplay);
  count.setAttribute('aria-live', 'off');
  restartAutoplay();
  gallery.querySelector('.gallery-thumbnails').hidden = false;
  count.hidden = false;
});
